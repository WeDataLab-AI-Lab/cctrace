// All inputs are indexed metadata. In particular this does not run the full
// timeline witness scan, enqueue analysis, or inspect trace snapshots/leases.
func readTurnContextVersion(ctx context.Context, tx pgx.Tx, id string) (v turnContextVersion, err error) {
	err = tx.QueryRow(ctx, `WITH current AS (
 SELECT COALESCE((SELECT revision FROM session_timeline_revisions WHERE session_id=$1),0) revision,epoch
 FROM session_timeline_policy_epoch WHERE only_row
 ) SELECT c.revision,c.epoch,COALESCE(p.timeline_state,''),COALESCE(f.coverage,''),COALESCE(f.agent,''),
 COALESCE(encode(p.source_witness,'hex')||':'||COALESCE(encode(p.timeline_hash,'hex'),'')||':'||encode(p.fact_output_hash,'hex')
 ||':'||p.mapping_version||':'||p.rules_version||':'||p.source_generation,'')
 FROM current c LEFT JOIN session_timeline_provenance p ON p.session_id=$1 AND p.source_revision=c.revision AND p.policy_epoch=c.epoch
 AND p.tracking='tracked' AND p.mapping_version=$2 AND p.rules_version=$3 AND p.source_generation>0
 AND octet_length(p.fact_output_hash)=32 AND ((p.timeline_state IN ('observed','undeterminable') AND octet_length(p.timeline_hash)=32)
 OR (p.timeline_state='truncated' AND p.timeline_hash IS NULL))
 LEFT JOIN session_analysis_facts f ON f.session_id=$1`, id, sessionTimelineMappingVersion, sessionfacts.RulesVersion).
		Scan(&v.Revision, &v.Epoch, &v.State, &v.Coverage, &v.Agent, &v.Mapping)
	return
}

// Acquire the session deletion barrier BEFORE establishing the repeatable-read
// snapshot. A transaction lock statement in repeatable read would take its
// snapshot before waiting for deletion and could resurrect deleted content.
func (s *PgStore) turnContextTx(ctx context.Context, id string) (pgx.Tx, func(), error) {
	pool, err := s.traceQueryPool(ctx)
	if err != nil {
		return nil, nil, err
	}
	conn, err := pool.Acquire(ctx)
	if err != nil {
		return nil, nil, err
	}
	unlock := func() {
		cleanup, cancel := context.WithTimeout(context.WithoutCancel(ctx), time.Second)
		defer cancel()
		if _, err := conn.Exec(cleanup, `SELECT pg_advisory_unlock_shared(hashtextextended($1,392))`, id); err != nil {
			_ = conn.Hijack().Close(cleanup)
			return
		}
		conn.Release()
	}
	if _, err = conn.Exec(ctx, `SELECT pg_advisory_lock_shared(hashtextextended($1,392))`, id); err != nil {
		// Cancellation can have an ambiguous lock outcome. Unlock on the same
		// connection (or discard it) before returning it to the pool.
		unlock()
		return nil, nil, err
	}
	tx, err := conn.BeginTx(ctx, pgx.TxOptions{IsoLevel: pgx.RepeatableRead, AccessMode: pgx.ReadOnly})
	if err != nil {
		unlock()
		return nil, nil, err
	}
	cleanup := func() {
		rollback, cancel := context.WithTimeout(context.WithoutCancel(ctx), time.Second)
		_ = tx.Rollback(rollback)
		cancel()
		unlock()
	}
	if _, err = tx.Exec(ctx, `SET LOCAL statement_timeout='1s'`); err != nil {
		cleanup()
		return nil, nil, err
	}
	return tx, cleanup, nil
}

// The exact tuple matches the membership index ordering; no body participates
// in cursor validation, sorting, or the extra key used to detect a next page.
const turnContextKeysSQL = `SELECT m.source_ts,m.source_uuid,m.source_record_id,m.source_record_type,m.source_profile_email
 FROM session_timeline_members m JOIN LATERAL (
 SELECT r.id FROM visible_session_records r WHERE r.session_id=m.session_id AND r.ts=m.source_ts AND r.uuid=m.source_uuid
 AND r.id=m.source_record_id AND r.record_type=m.source_record_type AND r.profile_email=m.source_profile_email
 AND ($3::text='' OR r.user_id=$3) AND ($4::text='' OR r.profile_email=$4) AND ($5::text='' OR r.login_email=$5)
 AND ` // ConversationProjectionPredicate is generated by the shared policy.

func turnContextKeys() string {
	return turnContextKeysSQL + ConversationProjectionPredicate() + ` LIMIT 1) allowed ON true WHERE m.session_id=$1 AND m.turn_key=$2`
}

func (s *PgStore) TurnContext(parent context.Context, id, turn string, a SessionAnalysisAccess, q TurnContextRequest) (TurnContextResponse, error) {
	out := TurnContextResponse{SessionID: id, TurnKey: turn, State: "pending", Records: []*SessionRecord{}}
	if id == "" || turn == "" || q.Limit < 0 || q.Limit > 100 {
		return out, ErrTurnContextInvalid
	}
	if q.Limit == 0 {
		q.Limit = 20
	}
	ctx, cancel := traceBudget(parent)
	defer cancel()
	tx, cleanup, err := s.turnContextTx(ctx, id)
	if err != nil {
		return out, err
	}
	defer cleanup()
	if err = authorizeTrace(ctx, tx, id, a); err != nil {
		return out, err
	}
	v, err := readTurnContextVersion(ctx, tx, id)
	if err != nil {
		return out, err
	}
	out.Revision, err = s.turnContextRevision(id, a, v)
	if err != nil {
		return out, err
	}
	if q.Revision != "" && q.Revision != out.Revision {
		return out, ErrTurnContextRevision
	}
	var after turnContextCursor
	if q.Cursor != "" {
		after, err = s.decodeTurnContextCursor(q.Cursor, out.Revision, turn)
		if err != nil {
			return out, err
		}
	}
	out.State = v.state()
	if out.State != "ready" {
		return out, tx.Commit(ctx)
	}
	var known, mapped bool
	err = tx.QueryRow(ctx, `SELECT EXISTS(SELECT 1 FROM session_turn_facts WHERE session_id=$1 AND turn_key=$2),
 EXISTS(SELECT 1 FROM session_timeline_members WHERE session_id=$1 AND turn_key=$2)`, id, turn).Scan(&known, &mapped)
	if err != nil {
		return out, err
	}
	if !known && !mapped {
		return out, ErrTurnContextTurnNotFound
	}
	if !mapped && v.State == "undeterminable" {
		out.State = "unavailable"
		return out, tx.Commit(ctx)
	}
	k := after.Key
	args := []any{id, turn, a.UserID, a.ProfileEmail, a.LoginEmail, k.Timestamp, k.UUID, k.RecordID, k.RecordType, k.ProfileEmail, q.Limit}
	keys := turnContextKeys()
	if q.Cursor != "" {
		var exists bool
		err = tx.QueryRow(ctx, `SELECT EXISTS(`+keys+` AND m.source_ts=$6 AND m.source_uuid=$7 AND m.source_record_id=$8 AND m.source_record_type=$9 AND m.source_profile_email=$10 AND $11::int>0)`, args...).Scan(&exists)
		if err != nil {
			return out, err
		}
		if !exists {
			return out, ErrTurnContextRevision
		}
	}
	var ts *time.Time
	if q.Cursor != "" {
		ts = &k.Timestamp
	}
	args[5] = ts
	rows, err := tx.Query(ctx, `WITH selected_keys AS MATERIALIZED (`+keys+`
 AND ($6::timestamptz IS NULL OR (m.source_ts,m.source_uuid,m.source_record_id,m.source_record_type,m.source_profile_email)>($6,$7,$8,$9,$10))
 ORDER BY m.source_ts,m.source_uuid,m.source_record_id,m.source_record_type,m.source_profile_email LIMIT ($11::int+1)
 ), page_keys AS MATERIALIZED (SELECT * FROM selected_keys ORDER BY source_ts,source_uuid,source_record_id,source_record_type,source_profile_email LIMIT $11)
 SELECT body.record,k.source_ts,k.source_uuid,k.source_record_id,k.source_record_type,k.source_profile_email,(SELECT count(*)>$11 FROM selected_keys)
 FROM page_keys k JOIN LATERAL (
 SELECT to_jsonb(r) record FROM visible_session_records r WHERE r.session_id=$1 AND r.ts=k.source_ts AND r.uuid=k.source_uuid
 AND r.id=k.source_record_id AND r.record_type=k.source_record_type AND r.profile_email=k.source_profile_email LIMIT 1
 ) body ON true ORDER BY k.source_ts,k.source_uuid,k.source_record_id,k.source_record_type,k.source_profile_email`, args...)
	if err != nil {
		return out, err
	}
	var last SessionTimelineKey
	var more bool
	for rows.Next() {
		var raw []byte
		if err = rows.Scan(&raw, &last.Timestamp, &last.UUID, &last.RecordID, &last.RecordType, &last.ProfileEmail, &more); err != nil {
			rows.Close()
			return out, err
		}
		var record SessionRecord
		if err = json.Unmarshal(raw, &record); err != nil {
			rows.Close()
			return out, err
		}
		out.Records = append(out.Records, &record)
	}
	rows.Close()
	if err = rows.Err(); err != nil {
		return out, err
	}
	if more {
		cursor, err := s.encodeTurnContextCursor(turnContextCursor{Revision: out.Revision, Turn: turn, Key: last})
		if err != nil {
			return out, err
		}
		out.NextCursor = &cursor
	}
	return out, tx.Commit(ctx)
}

