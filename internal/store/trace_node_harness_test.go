func TestTraceCodexInjectedMessagesAreNamedAndReadable(t *testing.T) {
	// Shared database fixtures must remain sequential.
	s := acquireTestStore(t)
	truncateTables(t, s)
	ctx := context.Background()
	base := time.Date(2026, 10, 18, 7, 20, 17, 0, time.UTC)
	message := func(role string, blocks []string, kinds ...string) json.RawMessage {
		return traceCodexMessageRow(t, role, blocks, kinds...).record.Raw
	}
	records := []*SessionRecord{
		{Ts: base, UUID: "input", RecordType: "user", Raw: message("user", []string{"You are working inside Orca"}, "user.text")},
		{Ts: base.Add(time.Millisecond), UUID: "rules", RecordType: "developer", Raw: message("developer", []string{"## Memory", "<permissions instructions> sandbox"}, "memories.instructions", "permissions.instructions")},
		{Ts: base.Add(2 * time.Millisecond), UUID: "hook", RecordType: "developer", Raw: message("developer", []string{"Recent commits: 8b73d65"}, "hooks.additional_context")},
	}
	for _, r := range records {
		r.SessionID, r.Agent, r.UserID, r.ProfileEmail, r.AccountID, r.SourceFile = "codex-items", "codex", "owner", "p", "a", "main"
	}
	if err := s.InsertSessionRecords(ctx, records); err != nil {
		t.Fatal(err)
	}
	a := SessionAnalysisAccess{User: true, UserID: "owner"}
	roots, err := s.TraceNodes(ctx, "codex-items", a, TraceNodesRequest{View: "flow", Limit: 20})
	if err != nil || len(roots.Nodes) == 0 {
		t.Fatalf("roots=%+v err=%v", roots, err)
	}
	children, err := s.TraceNodes(ctx, "codex-items", a, TraceNodesRequest{View: "flow", ParentID: roots.Nodes[0].NodeID})
	if err != nil {
		t.Fatal(err)
	}
	listed := map[string]sessiontrace.Node{}
	for _, child := range children.Nodes {
		listed[child.Title] = child
	}
	for title, items := range map[string]int{"메모리 안내 · 권한·샌드박스 지시": 2, "훅 추가 문맥 · Recent commits: 8b73d65": 1} {
		node, ok := listed[title]
		if !ok {
			t.Errorf("no row titled %q in %v", title, traceTitles(listed))
			continue
		}
		detail, err := s.TraceNodeDetail(ctx, "codex-items", a, node.NodeID)
		if err != nil {
			t.Fatal(err)
		}
		if detail.Node.Title != title || detail.Input.State != "observed" {
			t.Errorf("detail title=%q input=%+v", detail.Node.Title, detail.Input)
		}
		if got := detail.Interpretation; got == nil || len(got.Facts["items"].([]map[string]any)) != items {
			t.Errorf("%q interpretation=%+v", title, got)
		}
	}
}
