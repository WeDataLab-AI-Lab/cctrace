const traceClearCommand = "<command-name>/clear</command-name>\n            <command-message>clear</command-message>\n            <command-args></command-args>"

func TestTraceHarnessTextReadsClaudeCommandScaffolding(t *testing.T) {
	t.Parallel()
	long := strings.Repeat("output line ", 30)
	for _, tc := range []struct {
		name, text, command, title string
		want                       *TraceInterpretation
	}{
		{"clear", traceClearCommand, "clear", "/clear 명령", &TraceInterpretation{Kind: "slash_command", Facts: map[string]any{"command": "/clear", "args": ""}}},
		{"args", "<command-name>/model</command-name><command-message>model</command-message><command-args>opus</command-args>", "model", "/model 명령", &TraceInterpretation{Kind: "slash_command", Facts: map[string]any{"command": "/model", "args": "opus"}}},
		// A list row holds 96 characters, which can end before </command-name>
		// when the message tag comes first; the collected name stands in.
		{"cut", "<command-message>oh-my-claudecode:autopilot is running…</command-message>\n<command-name>/oh-my-cla", "oh-my-claudecode:autopilot", "/oh-my-claudecode:autopilot 명령", &TraceInterpretation{Kind: "slash_command", Facts: map[string]any{"command": "/oh-my-claudecode:autopilot"}}},
		{"caveat", "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>", "", "로컬 명령 안내문", &TraceInterpretation{Kind: "local_command_caveat"}},
		{"empty output", "<local-command-stdout></local-command-stdout>", "", "명령 출력 없음", &TraceInterpretation{Kind: "local_command_output", Facts: map[string]any{"output": ""}}},
		{"ansi output", "<local-command-stdout>Set model to \x1b[1mopus\x1b[22m</local-command-stdout>", "", "명령 출력 · Set model to opus", &TraceInterpretation{Kind: "local_command_output", Facts: map[string]any{"output": "Set model to opus"}}},
		{"error output", "<local-command-stderr>boom</local-command-stderr>", "", "명령 오류 출력 · boom", &TraceInterpretation{Kind: "local_command_error", Facts: map[string]any{"output": "boom"}}},
		{"long output", "<local-command-stdout>" + long + "</local-command-stdout>", "", "명령 출력 · " + string([]rune(strings.TrimSpace(long))[:60]) + "…", &TraceInterpretation{Kind: "local_command_output", Facts: map[string]any{"output": strings.TrimSpace(long)}}},
		{"typed", "please <command-name>/clear</command-name>", "", "", nil},
	} {
		t.Run(tc.name, func(t *testing.T) {
			title, got := traceHarnessText(tc.text, tc.command)
			if title != tc.title || !reflect.DeepEqual(got, tc.want) {
				t.Fatalf("title=%q interpretation=%+v want %q %+v", title, got, tc.title, tc.want)
			}
		})
	}
}

// The list reads the first 96 characters of a line's text and the detail reads
// all of it; both must name the row the same way.
func TestTraceHarnessTitleSurvivesListPreviewCut(t *testing.T) {
	t.Parallel()
	for _, text := range []string{traceClearCommand, "<local-command-stdout>" + strings.Repeat("x", 300) + "</local-command-stdout>"} {
		full, _ := traceHarnessText(text, "clear")
		cut, _ := traceHarnessText(string([]rune(text)[:96]), "clear")
		if full != cut {
			t.Fatalf("detail title %q differs from list title %q", full, cut)
		}
	}
}

