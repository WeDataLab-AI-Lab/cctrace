func TestTraceClaudeCommandAndSystemRowsAreInterpreted(t *testing.T) {
	// Shared database fixtures must remain sequential.
	s := acquireTestStore(t)
	truncateTables(t, s)
	ctx := context.Background()
	base := time.Date(2026, 10, 14, 8, 20, 47, 0, time.UTC)
	plugin := "<command-message>oh-my-claudecode:autopilot is running…</command-message>\n<command-name>/oh-my-claudecode:autopilot</command-name>\n<command-args>build it</command-args>"
	user := func(content string) json.RawMessage {
		raw, _ := json.Marshal(map[string]any{"type": "user", "message": map[string]any{"role": "user", "content": content}})
		return raw
	}
	records := []*SessionRecord{
		{Ts: base, UUID: "clear", RecordType: "user", CommandName: "clear", Raw: user(traceClearCommand)},
		{Ts: base.Add(time.Millisecond), UUID: "legacy", RecordType: "system", ParentUUID: "clear", Raw: json.RawMessage(`{"type":"system","message":null,"parentUuid":"clear"}`)},
		{Ts: base.Add(2 * time.Millisecond), UUID: "caveat", RecordType: "user", IsMeta: true, Raw: user("<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages.</local-command-caveat>")},
		{Ts: base.Add(10 * time.Second), UUID: "plugin", RecordType: "user", CommandName: "oh-my-claudecode:autopilot", Raw: user(plugin)},
		{Ts: base.Add(20 * time.Second), UUID: "duration", RecordType: "system", Raw: json.RawMessage(`{"type":"system","subtype":"turn_duration","durationMs":59574,"messageCount":113,"cctraceCollect":4}`)},
	}
	for _, r := range records {
		r.SessionID, r.Agent, r.UserID, r.ProfileEmail, r.SourceFile = "harness", "claude", "owner", "p", "main"
	}
	if err := s.InsertSessionRecords(ctx, records); err != nil {
		t.Fatal(err)
	}
	a := SessionAnalysisAccess{User: true, UserID: "owner"}
	roots, err := s.TraceNodes(ctx, "harness", a, TraceNodesRequest{View: "flow", Limit: 20})
	if err != nil {
		t.Fatal(err)
	}
	listed := map[string]sessiontrace.Node{}
	for _, root := range roots.Nodes {
		listed[root.Title] = root
		children, err := s.TraceNodes(ctx, "harness", a, TraceNodesRequest{View: "flow", ParentID: root.NodeID})
		if err != nil {
			t.Fatal(err)
		}
		for _, child := range children.Nodes {
			listed[child.Title] = child
		}
	}
	for _, title := range []string{"입력 구간 · /clear 명령", "/clear 명령", "시스템 기록 · 종류 미수집", "로컬 명령 안내문", "입력 구간 · /oh-my-claudecode:autopilot 명령", "턴 소요 시간 · 59.6초"} {
		if _, ok := listed[title]; !ok {
			t.Errorf("no row titled %q in %v", title, traceTitles(listed))
		}
	}
	interpreted := map[string]*TraceInterpretation{}
	for title, node := range listed {
		detail, err := s.TraceNodeDetail(ctx, "harness", a, node.NodeID)
		if err != nil {
			t.Fatal(err)
		}
		if detail.Node.Title != title {
			t.Errorf("detail title %q differs from list title %q", detail.Node.Title, title)
		}
		interpreted[title] = detail.Interpretation
	}
	if got := interpreted["시스템 기록 · 종류 미수집"]; got == nil || got.Kind != "system_kind_not_collected" || got.Facts["parent"] != "/clear 명령" {
		t.Errorf("uncollected system interpretation=%+v", got)
	}
	if got := interpreted["입력 구간 · /oh-my-claudecode:autopilot 명령"]; got == nil || got.Facts["args"] != "build it" {
		t.Errorf("plugin command interpretation=%+v", got)
	}
	if got := interpreted["로컬 명령 안내문"]; got == nil || got.Kind != "local_command_caveat" {
		t.Errorf("caveat interpretation=%+v", got)
	}
}

func traceTitles(nodes map[string]sessiontrace.Node) []string {
	titles := make([]string, 0, len(nodes))
	for title := range nodes {
		titles = append(titles, title)
	}
	return titles
}

func traceCodexMessageRow(t *testing.T, role string, blocks []string, kinds ...string) traceNodeRow {
	t.Helper()
	content := make([]any, len(blocks))
	for i, text := range blocks {
		content[i] = map[string]any{"type": "input_text", "text": text}
	}
	payload := map[string]any{"type": "message", "role": role, "content": content}
	if kinds != nil {
		payload["internal_chat_message_metadata_passthrough"] = map[string]any{"content_item_kinds": kinds}
	}
	raw, err := json.Marshal(map[string]any{"type": "response_item", "payload": payload})
	if err != nil {
		t.Fatal(err)
	}
	decoded, err := sessiontrace.DecodeObject(raw)
	if err != nil {
		t.Fatal(err)
	}
	return traceNodeRow{record: &SessionRecord{Agent: "codex", RecordType: role, Raw: raw}, raw: decoded}
}

